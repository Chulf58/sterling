// rulings-projection (decision 255f58b7, direction (a); closes board
// 8f81704a): a GENERATED READ-ONLY projection over the ruling corpus —
// ACTIVE decisions + anti_patterns — grouped by COMPONENT, the architecture.md
// pattern applied to the corpus instead of the registries. The corpus-growth
// question ("at 1000 records, what stops the store becoming a thing everybody
// writes to and nobody reads?") is not answered by making one record cheap to
// read (that is the digest projection, decision 87a12a1e) — it needs the WHOLE
// corpus to be visible at once, so a human can see three overlapping rulings
// on one subject that no per-record mechanism surfaces unprompted.
//
// COMPONENT = the first file_key's TOP-LEVEL path segment (e.g.
// 'packages/mcp-server/src/tools.ts' -> 'packages'; 'scripts/hooks/h20.mjs' ->
// 'scripts') — coarser than the TUI's two-segment dominant-bucket grouping on
// purpose: this projection's job is "which AREA has three rulings", not a
// drill-down tree. A record with no file_keys lands under '(uncomponented)'.
//
// Deterministic, like architecture.md: no wall-clock stamp — the as-of line
// derives from the corpus itself (max updated_at over decisions + anti_patterns),
// so an unchanged store regenerates byte-identical output, and
// check-projection-fresh.mjs can compare that stamp against the live store the
// same way it already does for architecture.md.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { openProject } from './lib/project.mjs';

const UNCOMPONENTED = '(uncomponented)';

function componentOf(fileKeys) {
  const first = Array.isArray(fileKeys) && fileKeys.length ? fileKeys[0] : undefined;
  if (typeof first !== 'string' || !first) return UNCOMPONENTED;
  return first.split('/')[0];
}

function clipTitle(title, n = 100) {
  const text = String(title ?? '').replace(/\s+/g, ' ').trim();
  return text.length <= n ? text : `${text.slice(0, n)}…`;
}

const { cwd, store } = openProject();
const decisions = store.query({ types: ['decision'], cap: 5000 });
const antiPatterns = store.query({ types: ['anti_pattern'], cap: 5000 });
const records = [...decisions, ...antiPatterns];

const buckets = new Map();
for (const r of records) {
  const key = componentOf(r.file_keys);
  const list = buckets.get(key) ?? [];
  list.push(r);
  buckets.set(key, list);
}

// Order: alphabetical over real components, '(uncomponented)' last — mirrors
// architecture.md's own "named sets, then a loud gap" ordering intuition.
const componentKeys = [...buckets.keys()].filter((k) => k !== UNCOMPONENTED).sort();
if (buckets.has(UNCOMPONENTED)) componentKeys.push(UNCOMPONENTED);

const SEVERITY_LABEL = { block: 'BLOCK', warn: 'WARN', info: 'INFO' };

function lineFor(r) {
  const clipped = clipTitle(r.title);
  if (r.type === 'anti_pattern') {
    const sev = SEVERITY_LABEL[r.severity ?? 'warn'] ?? 'WARN';
    return `- [${sev}] ${clipped} (\`${r.id}\`)`;
  }
  return `- ${clipped} (\`${r.id}\`)`;
}

const sections = componentKeys.map((key) => {
  const items = buckets
    .get(key)
    .slice()
    .sort((a, b) => (a.title ?? '').localeCompare(b.title ?? ''))
    .map(lineFor);
  return `## ${key}\n\n${items.join('\n')}\n`;
});

const newest = records.map((r) => r.updated_at).sort().at(-1) ?? 'empty store';
const md = `<!-- GENERATED by scripts/rulings-projection.mjs — DO NOT EDIT.
     Read-only projection over the ruling corpus: ACTIVE decisions + anti_patterns,
     grouped by component (decision 255f58b7-b1d4-4704-8858-570e1afe555d).
     Regenerate: node scripts/rulings-projection.mjs (store state as of ${newest}). -->

# Sterling rulings (generated)

Every ACTIVE decision and anti_pattern, grouped by the component named in its
first \`file_keys\` entry (\`${UNCOMPONENTED}\` for records with none). One line
per record: its clipped title and full id — \`knowledge_get <id>\` for the whole
record. This makes the CORPUS inspectable as a whole (decision
255f58b7-b1d4-4704-8858-570e1afe555d): a per-record query answers a question
someone asks; this answers the question nobody asked, like three overlapping
rulings on one subject sitting in the same component section below.

${sections.length ? sections.join('\n') : '_(no active decisions or anti_patterns in the store)_\n'}`;

writeFileSync(join(cwd, 'rulings.md'), md);
store.close();
console.log(
  `rulings.md written (${records.length} record(s): ${decisions.length} decision(s), ${antiPatterns.length} anti_pattern(s), ${componentKeys.length} component bucket(s))`
);
