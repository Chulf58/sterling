// Bundle hook scripts for shipping (CLAUDE.md invariant 4, spec §2.2):
// scripts/hooks/h*.mjs (which import workspace packages at author time) become
// standalone single-file hooks/<name>.mjs with no workspace imports at runtime.
// Requires built packages (npm run build) — bundles resolve package dist files.
//   node scripts/build-hooks.mjs [--out-dir <dir>]
// --out-dir builds somewhere OTHER than the live hooks/ surface. A test that
// needs a built bundle must use it: building in place puts whatever is in
// scripts/hooks/ live on disk for every subsequent hook call of the running
// session, which turns a mutation battery into a shipped sabotage (board
// 3e569411).
import { build } from 'esbuild';
import { readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve, relative } from 'node:path';
import { inFlightAdvisory } from './lib/dispatch-register.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const srcDir = join(here, 'hooks');

// Parsed STRICTLY: an unrecognized or malformed argument must refuse, never
// fall through to the default — the default writes the LIVE enforcement
// surface, so `--outdir` for `--out-dir` would silently do the one thing the
// flag exists to prevent (P5, fail loud).
const args = process.argv.slice(2);
let outDir = join(root, 'hooks');
for (let i = 0; i < args.length; i++) {
  if (args[i] !== '--out-dir') {
    console.error(`build-hooks: unrecognized argument '${args[i]}' — usage: build-hooks.mjs [--out-dir <dir>]`);
    process.exit(1);
  }
  const value = args[++i];
  if (!value || value.startsWith('--')) {
    console.error('build-hooks: --out-dir requires a directory argument');
    process.exit(1);
  }
  outDir = resolve(value);
}

// Wave-settle disclosure (board 54c451b4): a mid-wave bundle rebuild can race a
// coder's in-flight source edit (the 6ef262fc shape). Advisory only — never a gate.
const advisory = inFlightAdvisory(root, 'a bundle rebuilt now may race an in-flight edit of scripts/hooks sources.');
if (advisory) console.log(`build-hooks: ${advisory}`);

const entries = readdirSync(srcDir).filter((f) => f.startsWith('h') && f.endsWith('.mjs'));
for (const entry of entries) {
  await build({
    entryPoints: [join(srcDir, entry)],
    outfile: join(outDir, entry),
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node24',
    banner: { js: '// GENERATED by scripts/build-hooks.mjs — do not edit; edit scripts/hooks/ and rebuild.' },
  });
  console.log(`bundled: ${relative(root, join(outDir, entry)).split('\\').join('/')}`);
}
